def checks_vectors():
    """The URL-trail candidate list built in sensor.py:_process_packet()."""
    def checks_for(path, post_data=None):
        unquoted_post_data = _urllib.parse.unquote(post_data or "")
        checks = [path.rstrip('/')]
        if '?' in path:
            checks.append(path.split('?')[0].rstrip('/'))
            if '=' in path:
                checks.append(path[:path.index('=') + 1])
            _ = re.sub(r"(\w+=)[^&=]+", r"\g<1>", path)
            if _ not in checks:
                checks.append(_)
                if _.count('/') > 1:
                    checks.append("/%s" % _.split('/')[-1])
        elif post_data:
            checks.append("%s?%s" % (path, unquoted_post_data.lower()))
        if checks[-1].count('/') > 1:
            checks.append(checks[-1][:checks[-1].rfind('/')])
            checks.append(checks[0][checks[0].rfind('/'):].split('?')[0])
        return checks

    cases = [
        ("/malicious-login.php", None),
        ("/a/b/c.php?id=1&x=2", None),
        ("/submit", "q=1"),
        ("/a/b/c", None),
        ("/", None),
        ("/x?y", None),
        ("/a/b/c/d?p=1", None),
        ("/index.php?a=1&b=2&c=3", None),
        ("/deep/path/file.php?token=abc&next=%2Fhome", None),
        ("/x", "user=admin&pass=secret"),
    ]
    rows = []
    for path, post in cases:
        rows.append([path, post or "", "\x1f".join(checks_for(path, post))])
    return rows


def entropy_vectors():
    values = ["xkqwzlvbnmfghjd", "google", "aaaa", "a", "abcdefghij", "wnvxqzpltrkbdf", "facebook"]
    rows = []
    for part in values:
        probabilities = (float(part.count(c)) / len(part) for c in set(part))
        entropy = -sum(p * math.log(p) / math.log(2.0) for p in probabilities)
        consonants = sum(_ in S.CONSONANTS for _ in part)
        rows.append([part, "%.10f" % entropy, str(consonants)])
    return rows


