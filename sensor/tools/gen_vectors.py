def wildcard_trail_vectors():
    """For every wildcard/regex `(static)` trail, record whether CPython's `re` accepts it.

    `core/common.py:build_trails_regex()` silently drops the ones it cannot compile, so the
    Rust loader must make the SAME decision - otherwise one sensor matches a trail the other
    ignores. Patterns are taken from the operator's real trails.csv when available (real feeds
    do contain truncated, uncompilable patterns), plus a fixed set that is always included so
    the vector file is never empty.
    """
    wildcard = re.compile(r"[\].][*+]|\[[a-z0-9_.\-]+\]", re.I)
    seen = set()
    rows = []

    def add(trail):
        if trail in seen:
            return
        seen.add(trail)
        try:
            re.compile(trail)
            compiles = "1"
        except re.error:
            compiles = "0"
        rows.append([trail, compiles])

    # always-present cases, including a deliberately unterminated group
    for trail in (
        r"dga[0-9]+\.example\.com",
        r"[a-z]{5,}\.top",
        r"evil.*\.com",
        r"bad].+",
        r"x[abc_.-]y",
        r"\b(unterminated|group",
        r"[z-a]",
        r"(?P<dup>a)(?P<dup>b)",
        r"back\1reference",
        r"look(?=ahead)",
    ):
        add(trail)

    real = os.path.join(os.path.expanduser("~"), ".maltrail", "trails.csv")
    if os.path.isfile(real):
        import csv as _csv
        with open(real) as f:
            for row in _csv.reader(f):
                if len(row) == 3 and "static" in row[2] and wildcard.search(row[0]):
                    if re.escape(row[0]) != row[0]:
                        add(row[0])
    return rows


