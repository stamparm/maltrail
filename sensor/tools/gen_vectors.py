def enc(value):
    return (str(value)
            .replace("\\", "\\\\")
            .replace("\t", "\\t")
            .replace("\n", "\\n")
            .replace("\r", "\\r"))


def write(name, rows, header):
    path = os.path.join(OUT, name)
    with open(path, "w") as f:
        f.write("# GENERATED by sensor/tools/gen_vectors.py - do not edit\n")
        f.write("# %s\n" % header)
        for row in rows:
            f.write("\t".join(enc(_) for _ in row) + "\n")
    print("[i] %-24s %d vector(s)" % (name, len(rows)))


